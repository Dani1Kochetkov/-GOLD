-- GOLD DAYZ — схема базы данных (MySQL / MariaDB, utf8mb4)
-- Импортировать вручную не обязательно: сервер прогонит этот файл сам при старте.

CREATE TABLE IF NOT EXISTS accounts (
	id INT AUTO_INCREMENT PRIMARY KEY,
	login VARCHAR(32) NOT NULL UNIQUE,
	password_hash CHAR(64) NOT NULL,
	serial VARCHAR(64) NOT NULL DEFAULT '',
	created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS characters (
	id INT AUTO_INCREMENT PRIMARY KEY,
	account_id INT NOT NULL UNIQUE,
	pos_x FLOAT NOT NULL DEFAULT 195.7,
	pos_y FLOAT NOT NULL DEFAULT -933.1,
	pos_z FLOAT NOT NULL DEFAULT 30.7,
	heading FLOAT NOT NULL DEFAULT 0,
	blood FLOAT NOT NULL DEFAULT 12000,
	food FLOAT NOT NULL DEFAULT 100,
	water FLOAT NOT NULL DEFAULT 100,
	temperature FLOAT NOT NULL DEFAULT 36.6,
	shock FLOAT NOT NULL DEFAULT 0,
	bleeding TINYINT NOT NULL DEFAULT 0,
	fracture TINYINT NOT NULL DEFAULT 0,
	inventory TEXT,
	equipped TEXT,
	updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
	FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS vehicles (
	id INT AUTO_INCREMENT PRIMARY KEY,
	model VARCHAR(40) NOT NULL,
	pos_x FLOAT NOT NULL,
	pos_y FLOAT NOT NULL,
	pos_z FLOAT NOT NULL,
	heading FLOAT NOT NULL DEFAULT 0,
	fuel TINYINT NOT NULL DEFAULT 0,
	has_engine TINYINT NOT NULL DEFAULT 0,
	has_wheels TINYINT NOT NULL DEFAULT 0,
	storage TEXT,
	updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
